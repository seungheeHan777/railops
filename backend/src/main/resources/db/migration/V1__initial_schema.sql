CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE, password varchar(255) NOT NULL, name varchar(255) NOT NULL,
    role varchar(255) NOT NULL CHECK(role IN ('USER','ADMIN')),
    status varchar(255) NOT NULL CHECK(status IN ('ACTIVE','LOCKED','DELETED')),
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL
);
CREATE TABLE stations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL, code varchar(255) NOT NULL UNIQUE, city varchar(255) NOT NULL,
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL
);
CREATE TABLE routes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(255) NOT NULL,
    origin_station_id bigint NOT NULL REFERENCES stations(id), destination_station_id bigint NOT NULL REFERENCES stations(id),
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL
);
CREATE TABLE trains (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_no varchar(255) NOT NULL UNIQUE, train_type varchar(255) NOT NULL, name varchar(255) NOT NULL,
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL
);
CREATE TABLE cars (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, train_id bigint NOT NULL REFERENCES trains(id),
    car_no integer NOT NULL, seat_count integer NOT NULL, created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL,
    CONSTRAINT uk_cars_train_car_no UNIQUE(train_id, car_no)
);
CREATE TABLE seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, car_id bigint NOT NULL REFERENCES cars(id),
    seat_no varchar(255) NOT NULL, seat_type varchar(255) NOT NULL CHECK(seat_type IN ('STANDARD','PRIORITY','WINDOW','AISLE')),
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL, CONSTRAINT uk_seats_car_seat_no UNIQUE(car_id, seat_no)
);
CREATE TABLE train_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, train_id bigint NOT NULL REFERENCES trains(id), route_id bigint NOT NULL REFERENCES routes(id),
    operation_date date NOT NULL, departure_time timestamp(6) NOT NULL, arrival_time timestamp(6) NOT NULL,
    status varchar(255) NOT NULL CHECK(status IN ('SCHEDULED','DELAYED','CANCELED','COMPLETED')),
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL
);
CREATE TABLE schedule_seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_schedule_id bigint NOT NULL REFERENCES train_schedules(id), seat_id bigint NOT NULL REFERENCES seats(id),
    status varchar(255) NOT NULL CHECK(status IN ('AVAILABLE','HELD','RESERVED','BLOCKED')),
    held_by_user_id bigint REFERENCES users(id), hold_expires_at timestamp(6), version bigint,
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL,
    CONSTRAINT uk_schedule_seats_schedule_seat UNIQUE(train_schedule_id, seat_id)
);
CREATE TABLE reservations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reservation_no varchar(50) NOT NULL UNIQUE,
    user_id bigint NOT NULL REFERENCES users(id), train_schedule_id bigint NOT NULL REFERENCES train_schedules(id),
    status varchar(255) NOT NULL CHECK(status IN ('PENDING_PAYMENT','CONFIRMED','CANCELED','EXPIRED','PAYMENT_FAILED')),
    total_amount numeric(12,2) NOT NULL, hold_expires_at timestamp(6) NOT NULL,
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL
);
CREATE TABLE reservation_seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reservation_id bigint NOT NULL REFERENCES reservations(id),
    schedule_seat_id bigint NOT NULL REFERENCES schedule_seats(id), price numeric(12,2) NOT NULL, created_at timestamp(6) NOT NULL
);
CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reservation_id bigint NOT NULL UNIQUE REFERENCES reservations(id),
    payment_no varchar(50) NOT NULL UNIQUE, amount numeric(12,2) NOT NULL,
    status varchar(255) NOT NULL CHECK(status IN ('READY','SUCCESS','FAILED','CANCELED','EXPIRED')),
    requested_at timestamp(6) NOT NULL, approved_at timestamp(6), failed_at timestamp(6), canceled_at timestamp(6), expired_at timestamp(6),
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL
);
